"""
This Python script provides functions to load a PDF document,
extract its text content, and then tokenize that text into individual words
or punctuation marks. This is a foundational step for preparing documents
to be used in a Retrieval-Augmented Generation (RAG) agent.
"""

import PyPDF2
import nltk
from nltk.tokenize import word_tokenize
from typing import List, Optional
import sys # Import the sys module to access command-line arguments

# Ensure you have the necessary NLTK data downloaded.
# If you run into errors like "Resource punkt not found", uncomment and run the following lines:
# nltk.download('punkt')

def extract_text_from_pdf(pdf_path: str) -> Optional[str]:
    """
    Extracts all text content from a given PDF file.

    Args:
        pdf_path (str): The file path to the PDF document.

    Returns:
        Optional[str]: A single string containing all extracted text,
                       or None if an error occurs (e.g., file not found, PDF encrypted).
    """
    try:
        # Open the PDF file in binary read mode
        with open(pdf_path, 'rb') as file:
            # Create a PDF reader object
            reader = PyPDF2.PdfReader(file)

            # Initialize an empty list to store text from each page
            text_content = []

            # Iterate through each page and extract text
            for page_num in range(len(reader.pages)):
                page = reader.pages[page_num]
                text_content.append(page.extract_text())

            # Join all page texts into a single string
            return "\n".join(text_content)
    except FileNotFoundError:
        print(f"Error: The file at '{pdf_path}' was not found.")
        return None
    except PyPDF2.errors.PdfReadError:
        print(f"Error: Could not read PDF file '{pdf_path}'. It might be encrypted or corrupted.")
        return None
    except Exception as e:
        print(f"An unexpected error occurred while extracting text: {e}")
        return None

def tokenize_text(text: str) -> List[str]:
    """
    Tokenizes the given text into a list of words and punctuation marks.

    Args:
        text (str): The input text string.

    Returns:
        List[str]: A list of tokens.
    """
    if not isinstance(text, str):
        raise TypeError("Input 'text' must be a string.")

    # Use NLTK's word_tokenize to split text into tokens
    tokens = word_tokenize(text)
    return tokens

