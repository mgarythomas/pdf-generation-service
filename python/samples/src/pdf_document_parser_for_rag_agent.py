        print(document_text[:500] + ("..." if len(document_text) > 500 else ""))
        print("\n" + "="*50 + "\n")

        # 2. Tokenize the extracted text
        tokens = tokenize_text(document_text)

        print(f"--- Tokenization Results ---")
        print(f"Total number of tokens: {len(tokens)}")
        print(f"First 20 tokens: {tokens[:20]}")
        print(f"Last 20 tokens: {tokens[-20:]}")
        print("\n" + "="*50 + "\n")

        # Example of how you might use these tokens (e.g., for further processing)
